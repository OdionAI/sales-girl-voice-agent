"""Release the Lagos voice-auth sidecar from an uploaded Git revision.

The Azure connection string is read from stdin and written only to a root-only
environment file on the app VM. The active Compose service is the rollback unit.
"""

import argparse
import os
import subprocess
import sys
import time
from pathlib import Path

PROJECT = "odion-recovery-lagos"
BASE = Path("/opt/attentive/releases/recovery-20261009/compose.yaml")
SERVICE = "voice-auth"
CONTAINER = f"{PROJECT}-{SERVICE}-1"
SECRET = Path("/opt/attentive/secrets/voice-auth-wema.env")


def run(*args: str) -> str:
    return subprocess.check_output(args, text=True).strip()


def compose(override: Path) -> None:
    subprocess.run(
        ["docker", "compose", "-p", PROJECT, "-f", str(BASE), "-f", str(override),
         "up", "-d", "--no-deps", "--force-recreate", SERVICE],
        check=True,
    )


def healthy() -> bool:
    for _ in range(24):
        state = run("docker", "inspect", "--format", "{{.State.Health.Status}}", CONTAINER)
        if state == "healthy":
            return True
        if state == "unhealthy":
            return False
        time.sleep(5)
    return False


def write_override(path: Path, image: str, wema: bool, threshold: str = "0.60") -> None:
    # Fixed image names and paths are generated by this script, never caller data.
    text = f"services:\n  {SERVICE}:\n    image: {image}\n"
    if wema:
        value = float(threshold)
        if not 0.15 <= value <= 0.99:
            raise ValueError("voice-auth cosine threshold must be between 0.15 and 0.99")
        text += (
            f"    env_file:\n      - {SECRET}\n    environment:\n"
            f"      VOICE_AUTH_STORE: wema\n"
            f"      VOICE_AUTH_COSINE_THRESHOLD: \"{value:.2f}\"\n"
        )
    else:
        text += "    environment:\n      VOICE_AUTH_STORE: local\n"
    path.write_text(text)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--release", type=Path, required=True)
    parser.add_argument("--revision", required=True)
    parser.add_argument("--threshold", default=os.getenv("WEMA_VOICE_AUTH_COSINE_THRESHOLD", "0.60"))
    args = parser.parse_args()
    release = args.release.resolve()
    if not release.is_dir() or not (release / "deployment/lagos/voice-auth.Dockerfile").is_file():
        raise SystemExit("release sources missing")
    credential = sys.stdin.read().strip()
    if not credential.startswith("DefaultEndpointsProtocol=") or "AccountKey=" not in credential:
        raise SystemExit("Wema Blob connection string missing")
    old_image = run("docker", "inspect", "--format", "{{.Config.Image}}", CONTAINER)
    image = f"attentive/voice-auth:ci-{args.revision[:12]}"
    subprocess.run(
        ["docker", "build", "-f", str(release / "deployment/lagos/voice-auth.Dockerfile"),
         "--label", f"org.opencontainers.image.revision={args.revision}",
         "-t", image, str(release)], check=True,
    )
    SECRET.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    temporary = SECRET.with_suffix(".tmp")
    fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as stream:
        stream.write(f"WEMA_BLOB_CONNECTION_STRING={credential}\nWEMA_BLOB_CONTAINER=alatdevaudio\n")
    os.replace(temporary, SECRET)
    override = release / "voice-auth.override.yaml"
    write_override(override, image, True, args.threshold)
    try:
        compose(override)
        if not healthy():
            raise RuntimeError("voice-auth health check failed")
    except Exception:
        rollback = release / "voice-auth.rollback.yaml"
        write_override(rollback, old_image, False)
        compose(rollback)
        raise
    print(f"voice-auth revision {args.revision} healthy")


if __name__ == "__main__":
    main()
